"""TradeDecision — Execution FROZEN v1.0 §4/§8. The single seam between
the Strategy Engine and the Execution Engine. Immutable after creation: a
material change requires a brand new decision_id from a fresh canonical
pipeline evaluation, never a mutation of an existing one (Implementation
Spec v1.0 §8) — this is enforced for free by UTCModel's frozen=True."""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from enum import Enum
from typing import Optional

from pydantic import field_validator, model_validator

from core.domain.common import Direction, Environment, UTCModel, ensure_utc


class EntryType(str, Enum):
    MARKET = "MARKET"  # the only entry_type the frozen strategy spec permits


class TradeDecision(UTCModel):
    decision_id: str
    strategy_version: str
    config_hash: str
    setup_id: str
    symbol: str
    direction: Direction
    entry_type: EntryType = EntryType.MARKET
    intended_entry_price: Decimal
    execution_price_policy: Decimal  # max_acceptable_slippage, ATR-normalized
    stop_loss: Decimal
    take_profit_1: Decimal
    take_profit_2: Decimal
    tp_allocation: tuple[Decimal, Decimal]  # (TP1 %, TP2 %) — PROVISIONAL 30/70
    position_size: Decimal
    risk_amount: Decimal
    risk_percentage: Decimal
    decision_timestamp: datetime
    decision_expiry: datetime
    originating_event_ids: tuple[str, ...]
    score: Decimal
    environment: Environment
    idempotency_key: str

    @field_validator("decision_timestamp", "decision_expiry")
    @classmethod
    def _utc(cls, value: datetime) -> datetime:
        return ensure_utc(value)

    @model_validator(mode="after")
    def _invariants(self) -> "TradeDecision":
        if self.decision_expiry <= self.decision_timestamp:
            raise ValueError("decision_expiry must be after decision_timestamp")
        if abs(sum(self.tp_allocation) - Decimal("100")) > Decimal("0.001"):
            raise ValueError("tp_allocation percentages must sum to 100")
        if self.position_size <= 0:
            raise ValueError("position_size must be positive")
        if self.risk_percentage <= 0:
            raise ValueError("risk_percentage must be positive")
        if self.direction == Direction.BULLISH and self.stop_loss >= self.intended_entry_price:
            raise ValueError("bullish stop_loss must be below intended_entry_price")
        if self.direction == Direction.BEARISH and self.stop_loss <= self.intended_entry_price:
            raise ValueError("bearish stop_loss must be above intended_entry_price")
        return self

    def is_expired(self, at: datetime) -> bool:
        """OD3 (Execution FROZEN v1.0): an expired decision is aborted,
        never resubmitted and never auto-regenerated by this check —
        regeneration can only come from a fresh canonical pipeline run."""
        return ensure_utc(at) > self.decision_expiry
